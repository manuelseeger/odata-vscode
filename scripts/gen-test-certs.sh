#!/usr/bin/env bash
# Regenerates the TEST-ONLY TLS fixtures used by src/test/integration/tls.test.ts.
# These keys are public and must never be trusted outside the test suite.
#
#   ./scripts/gen-test-certs.sh
#
# Certificates are valid for 100 years. Rerun this script if they ever expire
# or if the fixture layout changes.
set -euo pipefail

OUT="$(cd "$(dirname "$0")/.." && pwd)/src/test/testdata/tls"
PASS="test-passphrase"
DAYS=36500
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

rm -rf "$OUT"
mkdir -p "$OUT"

ca() { # name subject
    openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days "$DAYS" \
        -keyout "$WORK/$1-key.pem" -out "$OUT/$1.pem" -subj "$2" \
        -addext "basicConstraints=critical,CA:TRUE" \
        -addext "keyUsage=critical,keyCertSign,cRLSign" 2>/dev/null
}

leaf() { # name subject ca extensions
    openssl req -newkey rsa:2048 -nodes -sha256 \
        -keyout "$OUT/$1-key.pem" -out "$WORK/$1.csr" -subj "$2" 2>/dev/null
    printf '%s\n' "basicConstraints=CA:FALSE" "$4" >"$WORK/$1.ext"
    openssl x509 -req -sha256 -days "$DAYS" -in "$WORK/$1.csr" \
        -CA "$OUT/$3.pem" -CAkey "$WORK/$3-key.pem" -CAcreateserial \
        -extfile "$WORK/$1.ext" -out "$OUT/$1.pem" 2>/dev/null
}

# Trusted CA: issues the server certificate and the accepted client certificate.
ca ca "/CN=OData Test CA"
leaf server "/CN=localhost" ca \
    "subjectAltName=IP:127.0.0.1,DNS:localhost
extendedKeyUsage=serverAuth"
leaf client "/CN=odata-test-client" ca "extendedKeyUsage=clientAuth"

# Untrusted CA: issues a client certificate the server must reject.
ca untrusted-ca "/CN=OData Untrusted Test CA"
leaf untrusted-client "/CN=odata-untrusted-client" untrusted-ca "extendedKeyUsage=clientAuth"

# Passphrase-protected variants of the accepted client identity.
openssl pkey -in "$OUT/client-key.pem" -aes256 -passout "pass:$PASS" \
    -out "$OUT/client-key-encrypted.pem"
openssl pkcs12 -export -in "$OUT/client.pem" -inkey "$OUT/client-key.pem" \
    -certfile "$OUT/ca.pem" -name odata-test-client -passout "pass:$PASS" \
    -out "$OUT/client.pfx"

# The CA certificates are kept; their keys are discarded so nothing new can be signed.
rm -f "$OUT"/*.srl

cat >"$OUT/README.md" <<EOF
# TLS test fixtures

**Test-only keys. Never trust these certificates outside the test suite.**

Generated by \`scripts/gen-test-certs.sh\`; rerun it to regenerate. Used by
\`src/test/integration/tls.test.ts\`.

| File | Purpose |
| --- | --- |
| \`ca.pem\` | Trusted CA (server trust anchor and accepted client issuer) |
| \`server.pem\`, \`server-key.pem\` | Server identity for \`127.0.0.1\` / \`localhost\` |
| \`client.pem\`, \`client-key.pem\` | Accepted client identity (\`CN=odata-test-client\`) |
| \`client-key-encrypted.pem\` | Same client key, encrypted with passphrase \`$PASS\` |
| \`client.pfx\` | Same client identity as PKCS#12, passphrase \`$PASS\` |
| \`untrusted-ca.pem\` | CA the server does not trust |
| \`untrusted-client.pem\`, \`untrusted-client-key.pem\` | Client identity the server must reject |
EOF

echo "Wrote TLS fixtures to $OUT"
